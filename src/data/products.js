const slugify = (value = '') =>
  value
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

const getImageByProductName = (nombre) => {
  if (!nombre) return null;

  const slug = slugify(nombre);

  const match = Object.entries(imagenesDisponibles).find(([path]) => {
    const fileName = path.split('/').pop().replace(/\.webp$/i, '');
    return slugify(fileName) === slug;
  });

  return match ? match[1] : null;
};

